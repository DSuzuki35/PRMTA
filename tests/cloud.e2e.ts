import { test, expect } from '@playwright/test';
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, unlinkSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createHost, type Host } from '../server/host';
import { defaultPreferences } from '../shared/model';
let host: Host, root: string, folder: string;
test.beforeEach(async () => { root = mkdtempSync(join(tmpdir(), 'prmta-workspace-')); folder = join(root, 'cloud'); mkdirSync(folder); host = await createHost({ dataDir: join(root, 'local'), port: 0, staticDir: resolve('dist') }); });
test.afterEach(async () => { await host.close(); rmSync(root, { recursive: true, force: true }); });
const post = (path: string, body: unknown) => fetch(`${host.origin}/api${path}`, { method: 'POST', headers: { Authorization: `Bearer ${host.tokens.admin}`, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
test('folder switching asks before copying, keeps libraries separate, and rejects stale saves', async ({ page }) => {
  const saved = await (await post('/scripts', { draft: { id: crypto.randomUUID(), title: 'Local story', content: 'Local words' }, expectedHeads: [] })).json();
  writeFileSync(join(folder, 'Existing.txt'), 'Cloud words');
  await page.goto(host.url('admin')); await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Cloud library folder', { exact: true }).fill(folder);
  await page.getByRole('button', { name: 'Open cloud library', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Switch script library' })).toBeVisible();
  expect(host.library.get(saved.id)).toBeTruthy(); expect(readdirSync(folder)).toEqual(['Existing.txt']);
  await page.getByRole('button', { name: 'Open folder only', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  await expect(page.locator('.script-card h3')).toHaveText(['Existing']);
  await expect(page.locator('.storage-badge')).toHaveText('Cloud folder');
  expect((await post('/scripts', { draft: saved, expectedHeads: saved.heads, workspace: 'local' })).status).toBe(409);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Use local library', exact: true }).click();
  await page.getByRole('button', { name: 'Open local library', exact: true }).click();
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  await expect(page.locator('.script-card h3')).toHaveText(['Local story']);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Cloud library folder', { exact: true }).fill(folder);
  await page.getByRole('button', { name: 'Open cloud library', exact: true }).click();
  await page.getByRole('button', { name: 'Copy current scripts', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(readdirSync(folder).filter(f => f.endsWith('.txt')).sort()).toEqual(['Existing.txt', 'Local story.txt']);
});
test('cloud edits and trash change the actual TXT, external deletion reaches the library', async ({ page }) => {
  writeFileSync(join(folder, 'Existing.txt'), 'Cloud words'); await post('/workspace', { folder, copyCurrent: false });
  await page.goto(host.url('admin')); await page.getByRole('button', { name: 'Library', exact: true }).click();
  await page.locator('.script-card').click(); await page.getByLabel('Script title').fill('Renamed');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect.poll(() => readdirSync(folder).filter(f => f.endsWith('.txt'))).toEqual(['Renamed.txt']);
  await page.getByRole('button', { name: 'Move to trash', exact: true }).click();
  await expect.poll(() => readdirSync(folder).filter(f => f.endsWith('.txt'))).toEqual([]);
  await page.getByRole('button', { name: 'Restore', exact: true }).click();
  await expect.poll(() => readdirSync(folder).filter(f => f.endsWith('.txt'))).toEqual(['Renamed.txt']);
  writeFileSync(join(folder, 'Renamed.txt'), 'Changed outside PRMTA'); await post('/sync', {});
  await expect(page.getByLabel('Script text')).toHaveValue('Changed outside PRMTA');
  unlinkSync(join(folder, 'Renamed.txt')); await post('/sync', {});
  await expect(page.locator('.script-card')).toHaveCount(0);
});
